QUERY 01: Total Revenue Analysis
Objective: Calculate total revenue
from completed orders only

SELECT SUM(oi.quantity*oi.unit_price) As total_revenue
FROM orders as o
LEFT JOIN order_items as oi
ON o.order_id = oi.order_id 
WHERE o.status='Completed';
--------------------------------------------------------------
QUERY 02: Monthly Sales Analysis
Objective: Calculate total revenue generated in each month.
         (Calculate monthly revenue from completed orders.)
         
SELECT DATE_FORMAT(o.order_date,'%Y-%M') As Sales_Month,
SUM(oi.quantity*oi.unit_price) As Monthly_Revenue
FROM orders as o
LEFT JOIN order_items as oi
ON o.order_id = oi.order_id 
WHERE o.status='Completed'
GROUP BY DATE_FORMAT(o.order_date,'%Y-%M')
ORDER BY Monthly_Revenue DESC;
-------------------------------------------------------------------
QUERY 03: Top 5 Best-Selling Products
Objective: Identify the top 5 products with the highest quantity sold.

SELECT SUM(oi.quantity) As Total_quantity_sold, p.product_name
FROM order_items as oi 
JOIN products as p
    ON p.product_id = oi.product_id
JOIN orders o 
    ON oi.order_id = o.order_id
WHERE o.status='Completed'
GROUP BY p.product_id, p.product_name
ORDER BY Total_quantity_sold DESC
LIMIT 5;
-------------------------------------------------------------

QUERY 04: Total Orders by Order Status
Objective: Calculate the total number of orders in each status.

SELECT COUNT(status) as Number_of_orders, status
FROM orders o
GROUP BY status
ORDER BY 1 DESC;
--------------------------------------------------------------------

QUERY 05: Customer-Wise total spending  
Objective: Calculate how much each customer has spent on completed orders.

SELECT o.customer_id ,SUM(oi.quantity*oi.unit_price) as total_spent
FROM orders as o
JOIN order_items oi
    ON o.order_id=oi.order_id
WHERE o.status='Completed'
GROUP BY o.customer_id
ORDER BY 1 DESC;
----------------------------------------------------------------

QUERY 06: Average Order Value 
Objective: Calculate the average value of completed orders.

SELECT AVG(order_total) AS
      Average_order_value
FROM (
      SELECT o.order_id, 
         SUM(oi.quantity*oi.unit_price) As order_total
      FROM orders o
      JOIN order_items oi
        ON o.order_id=oi.order_id
      WHERE o.status='Completed'
      GROUP BY  o.order_id
      ) As order_totals;
------------------------------------------------------------

QUERY 07: Top 5 Highest Spending Customers
Objective: Identify the 5 customers who spend the most money.

SELECT o.customer_id,
    SUM(oi.quantity*oi.unit_price) As total_spending
FROM orders o
JOIN order_items oi
  ON o.order_id=oi.order_id
WHERE o.status='Completed'
GROUP BY o.customer_id
ORDER BY total_spending DESC
LIMIT 5; 
--------------------------------------------------------------

QUERY 08: Product-Wise Revenue Analysis
Objective: Calculate Revenue generated by each product.

SELECT  product_name,
     SUM(oi.quantity*oi.unit_price) As product_revenue
FROM products p
JOIN order_items oi
   ON p.product_id=oi.product_id
JOIN orders o
   ON o.order_id=oi.order_id
WHERE o.status='Completed'
GROUP BY p.product_id, p.product_name
ORDER BY 1 DESC;
----------------------------------------------------------

QUERY 09:  Highest Value Orders
Objective: Find the top 10 orders with the highest revenue.

SELECT o.order_id,
     SUM(oi.quantity*oi.unit_price) As order_value
FROM orders o
JOIN order_items oi
   ON o.order_id=oi.order_id
WHERE o.status='Completed'
GROUP BY order_id
ORDER BY 1 DESC
LIMIT 10;
-------------------------------------------------------------

QUEERY 10: Monthly Order Count
Objective: Calculate the number of completed orders in each month.

SELECT DATE_FORMAT(o.order_date, '%y-%m') As order_month,
      COUNT(DISTINCT o.order_id) As total_orders 
FROM orders o
WHERE o.status='Completed'
GROUP BY  DATE_FORMAT(o.order_date,'%y-%m')
ORDER BY 1 DESC;
----------------------------------------------------------

QUERY 11: Order Value Classification
Objective: Classify completed orders into High, Medium and Low value categories.

SELECT order_id,
       order_value,
       CASE
          WHEN order_value >= 5000 THEN 'High Value'
          WHEN order_value >= 2000 THEN 'Medium Value'
          ELSE 'Low Value'
       END AS order_category
FROM (
    SELECT
       o.order_id,
       SUM(oi.quantity*oi.unit_price) As order_value
    FROM orders o 
    JOIN order_items oi
       ON o.order_id = oi.order_id
    WHERE o.status = 'Completed'
    GROUP BY o.order_id
) As order_summary;
---------------------------------------------------------

QUERY 12: Overall Sales
          Performance Summary
Objective: Generate an overall summary of completed sales.

SELECT 
     COUNT(DISTINCT o.order_id) As total_orders,
     SUM(oi.quantity) As total_units_sold,
     SUM(oi.quantity*oi.unit_price) As total_revenue,
     AVG(oi.unit_price) As average_unit_price
FROM orders o
JOIN order_items oi
   ON o.order_id = oi.order_id
WHERE o.status = 'Completed';

